interface IconProps {
  name: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  "aria-hidden"?: boolean;
}

export function Icon({
  name,
  size = 16,
  strokeWidth = 1.8,
  className,
  "aria-hidden": ariaHidden = true,
}: IconProps) {
  const Component = ICONS[name] ?? Circle;
  return (
    <Component
      aria-hidden={ariaHidden}
      className={className}
      size={size}
      strokeWidth={strokeWidth}
    />
  );
}
